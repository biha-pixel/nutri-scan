/**
 * Food Recognition & Analysis Types (Mobile Client)
 *
 * These types define the contract between the mobile frontend
 * and the Next.js backend API for the unified food analysis flow.
 *
 * IMPORTANT DESIGN RULES:
 * 1. The AI identifies food only — it never generates nutrition values.
 * 2. Nutrition data comes from USDA FoodData Central (authoritative source).
 * 3. Highlights are deterministic and rule-based (FDA Daily Values), not AI-generated.
 * 4. `null` means "data not available" — `0` means "verified zero."
 */

// ─── Vision-Only Types ─────────────────────────────────────────────

/**
 * A single food item identified by the vision service.
 * This is what the AI returns — names and confidence, nothing nutritional.
 */
export interface FoodItem {
  /** Display name of the food (e.g., "Banana", "Grilled Chicken") */
  name: string;
  /** Standardized name used for nutritional database lookup (e.g., "Bananas, raw") */
  canonicalName: string;
  /** AI confidence score between 0.0 and 1.0 */
  confidence: number;
  /** Brief description of the item observed in the image */
  description: string;
  /** Rough portion estimate (e.g., "1 medium", "100g", "1 cup") */
  estimatedPortion: string;
}

/**
 * Result returned by the legacy food recognition API endpoint (/api/scan).
 * Kept for backward compatibility.
 */
export interface FoodRecognitionResult {
  /** Array of identified food items */
  items: FoodItem[];
  /** Overall quality rating of the analyzed image */
  imageQuality: 'good' | 'poor' | 'unrecognizable';
  /** Optional message or notes from the vision service */
  message?: string;
}

// ─── Nutrition Types (mirroring backend) ────────────────────────────

/**
 * Macronutrient values for a food item.
 * All values in grams per serving. `null` = data not available.
 */
export interface Macronutrients {
  protein: number | null;
  totalFat: number | null;
  saturatedFat: number | null;
  carbohydrates: number | null;
  fiber: number | null;
  sugar: number | null;
}

/**
 * Micronutrient values for a food item.
 * Units vary per nutrient. `null` = data not available.
 */
export interface Micronutrients {
  sodium: number | null;
  cholesterol: number | null;
  potassium: number | null;
  vitaminA: number | null;
  vitaminC: number | null;
  calcium: number | null;
  iron: number | null;
}

/**
 * Complete normalized nutrition data for a single food item.
 */
export interface NutritionData {
  foodName: string;
  source: string;
  sourceId: string;
  servingSize: number;
  servingUnit: string;
  calories: number | null;
  macronutrients: Macronutrients;
  micronutrients: Micronutrients;
  sourceUrl: string | null;
  matchConfidence: 'exact' | 'close' | 'approximate';
}

// ─── Highlight Types ────────────────────────────────────────────────

export type HighlightLevel = 'high' | 'good' | 'low' | 'info';
export type HighlightCategory = 'macronutrient' | 'micronutrient' | 'mineral' | 'energy_balance';

/**
 * A single deterministic nutritional highlight.
 * Generated by rule-based engine on the backend, not by AI.
 */
export interface NutritionHighlight {
  text: string;
  description: string;
  nutrient: string;
  level: HighlightLevel;
  category: HighlightCategory;
  referenceBasis: string;
  priority: number;
}

// ─── Nutrition Search Candidate (for "Change food" flow) ────────────

export interface NutritionSearchCandidate {
  sourceId: string;
  source: string;
  foodName: string;
  description: string | null;
  dataType: string | null;
  score: number;
}

// ─── Unified Analyze-Food Response ──────────────────────────────────

export type NutritionStatus = 'found' | 'ambiguous' | 'not_found' | 'unavailable' | 'error';

/**
 * A fully analyzed food item, combining vision recognition + nutrition + highlights.
 */
export interface AnalyzedFoodItem {
  name: string;
  canonicalName: string;
  confidence: number;
  description: string;
  estimatedPortion: string;
  nutritionStatus: NutritionStatus;
  nutrition: NutritionData | null;
  highlights: NutritionHighlight[];
  candidates?: NutritionSearchCandidate[];
  errorMessage?: string;
}

/**
 * The data payload returned by POST /api/analyze-food on success.
 */
export interface FoodAnalysisResult {
  items: AnalyzedFoodItem[];
  imageQuality: 'good' | 'poor' | 'unrecognizable';
  message?: string;
  analyzedAt: string;
}

// ─── API Response Wrappers ──────────────────────────────────────────

export interface ApiError {
  code: string;
  message: string;
}

export type ScanApiResponse =
  | { success: true; data: FoodRecognitionResult }
  | { success: false; error: ApiError };

export type AnalyzeFoodApiResponse =
  | { success: true; data: FoodAnalysisResult }
  | { success: false; error: ApiError };

// ─── Scan History & Persistence Types ──────────────────────────────

export interface SavedScanItem {
  id: string;
  scanId: string;
  foodName: string;
  confidence: number;
  nutritionSource: string;
  nutritionId: string | null;
  servingBasis: string;
  nutrients: {
    calories?: number | null;
    macronutrients?: Macronutrients;
    micronutrients?: Micronutrients;
  };
  highlights: NutritionHighlight[];
  createdAt: string;
}

export interface SavedScan {
  id: string;
  userId: string | null;
  imageUrl: string | null;
  createdAt: string;
  items: SavedScanItem[];
}

export interface ScanHistoryData {
  scans: SavedScan[];
  total: number;
  limit: number;
  offset: number;
  hasMore: boolean;
}

export type ScanHistoryApiResponse =
  | { success: true; data: ScanHistoryData }
  | { success: false; error: ApiError };

export type SavedScanApiResponse =
  | { success: true; data: SavedScan }
  | { success: false; error: ApiError };

export type DeleteScanApiResponse =
  | { success: true; data: { deleted: boolean; id: string } }
  | { success: false; error: ApiError };

// Payload for POST /api/scans
export interface CreateScanPayloadItem {
  foodName: string;
  confidence: number;
  nutritionSource: string;
  nutritionId: string | null;
  servingBasis: string;
  nutrients: {
    calories?: number | null;
    macronutrients?: Macronutrients;
    micronutrients?: Micronutrients;
  };
  highlights: NutritionHighlight[];
}

export interface CreateScanPayload {
  userId?: string | null;
  imageUrl?: string | null;
  items: CreateScanPayloadItem[];
}

export type AnalysisLoadingStage =
  | 'preparing'
  | 'analyzing'
  | 'nutrition'
  | 'finalizing';

export type AnalysisErrorCode =
  | 'NO_FOOD_DETECTED'
  | 'UNCERTAIN_FOOD'
  | 'NUTRITION_UNAVAILABLE'
  | 'NETWORK_ERROR'
  | 'AI_FAILURE'
  | 'SERVER_ERROR'
  | 'INVALID_IMAGE';
